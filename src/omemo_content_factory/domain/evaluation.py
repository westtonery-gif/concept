"""Evaluation domain model — a QA / quality verdict on a candidate Artifact.

A child entity of the Run aggregate root (DOMAIN_MODEL.md §2.13, §9.1): the structured judgement
"passed / risk / reject" plus its flags, the basis for the Content Director's routing and the
context shown to the human. Its QA case is the **fail closed** quality/compliance gate of the
health domain (PROJECT.md §10, §12): only a ``PASSED`` verdict lets an Artifact be approved; a
missing, pending, ``FLAGGED`` or ``FAILED`` one keeps the gate shut (enforced by Run, ADR-0018 §5).

Created and decided **only via Run** (``Run.open_evaluation`` / ``Run.record_evaluation``). The
verdict is produced outside the domain (a QA evaluator, invoked by the application layer) and Run
only persists it — evaluation-ownership Variant A (ADR-0013 §8), as for Schema validation.

This module depends only on stdlib and ``domain.errors``; its references (``run_id``,
``artifact_ref``) are opaque ``str`` (ADR-0003 §3), avoiding any import cycle.

Scope note (ADR-0018): evaluating an Output, a confidence score, a criteria (Prompt version)
reference and an audit timestamp are deferred.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import TypeAlias

from omemo_content_factory.domain.errors import DomainError

EvaluationId: TypeAlias = str
"""Opaque, stable identifier of an Evaluation (ADR-0018 §2). Generated by the owning Run."""


class EvaluationStatus(Enum):
    """The lifecycle states of an Evaluation (DOMAIN_MODEL.md §2.13).

    An evaluation is created ``PENDING`` and decided exactly once. ``PASSED`` ("passed"),
    ``FLAGGED`` ("risk") and ``FAILED`` ("reject") are terminal verdicts. Only ``PASSED`` lets the
    evaluated Artifact be approved (fail closed, ADR-0018 §5).
    """

    PENDING = "pending"
    PASSED = "passed"
    FLAGGED = "flagged"
    FAILED = "failed"


# --- Read-only snapshot ------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class EvaluationView:
    """Immutable, read-only snapshot of an Evaluation (ADR-0018 §2).

    The only representation that leaves the aggregate; an evaluation changes only through its Run.
    """

    evaluation_id: EvaluationId
    run_id: str
    artifact_ref: str
    kind: str
    status: EvaluationStatus
    flags: tuple[str, ...]


# --- Domain events -----------------------------------------------------------------------
# Recorded in the owning Run's existing event log (ADR-0018 §8).


@dataclass(frozen=True, slots=True)
class EvaluationEvent:
    """Base type for Evaluation domain events. Carries the owning Run id and the evaluation id."""

    run_id: str
    evaluation_id: str


@dataclass(frozen=True, slots=True)
class EvaluationCompleted(EvaluationEvent):
    """Emitted when a verdict is recorded (DOMAIN_MODEL.md §10). Carries subject, verdict, flags."""

    artifact_ref: str
    verdict: EvaluationStatus
    flags: tuple[str, ...] = ()


# --- Domain errors -----------------------------------------------------------------------
# Rooted at the shared ``DomainError`` (ADR-0017). Actor authorisation reuses Run's
# UnauthorizedActorError; the approval gate raises ``ArtifactQaNotPassedError`` (domain.artifact).


class EvaluationDomainError(DomainError):
    """Base class for all Evaluation domain-rule violations."""


class InvalidEvaluationTransitionError(EvaluationDomainError):
    """A verdict was requested on a decided evaluation, or the verdict is not terminal."""


class ImmutableEvaluationAttributeError(EvaluationDomainError):
    """An attempt was made to change an immutable attribute of an Evaluation.

    Guards the internal entity for parity with the other child entities. Because only an
    ``EvaluationView`` snapshot leaves the aggregate, this is a structural defence.
    """


# --- Allowed transitions -----------------------------------------------------------------

# An evaluation is decided exactly once: from PENDING to one terminal verdict (ADR-0018 §2).
_TERMINAL_VERDICTS: frozenset[EvaluationStatus] = frozenset(
    {EvaluationStatus.PASSED, EvaluationStatus.FLAGGED, EvaluationStatus.FAILED}
)

_IMMUTABLE_EVALUATION_ATTRIBUTES = frozenset(
    {
        "evaluation_id",
        "run_id",
        "artifact_ref",
        "kind",
        "_evaluation_id",
        "_run_id",
        "_artifact_ref",
        "_kind",
    }
)


# --- Evaluation entity (internal — constructed only by Run) -------------------------------


class Evaluation:
    """The Evaluation child entity — one verdict on a candidate Artifact.

    **Not** a public API: created only by ``Run.open_evaluation`` and decided only by
    ``Run.record_evaluation``. ``__slots__`` + a guarded ``__setattr__`` make identity, subject and
    kind write-once; only the verdict (``status`` + ``flags``) is set, exactly once.
    """

    __slots__ = (
        "_artifact_ref",
        "_evaluation_id",
        "_flags",
        "_kind",
        "_run_id",
        "_status",
    )

    _evaluation_id: EvaluationId
    _run_id: str
    _artifact_ref: str
    _kind: str
    _status: EvaluationStatus
    _flags: tuple[str, ...]

    def __init__(
        self, evaluation_id: EvaluationId, run_id: str, artifact_ref: str, kind: str
    ) -> None:
        object.__setattr__(self, "_evaluation_id", evaluation_id)
        object.__setattr__(self, "_run_id", run_id)
        object.__setattr__(self, "_artifact_ref", artifact_ref)
        object.__setattr__(self, "_kind", kind)
        self._status = EvaluationStatus.PENDING
        self._flags = ()

    def __setattr__(self, name: str, value: object) -> None:
        """Reject reassignment of immutable attributes and their backing fields (ADR-0018 §2)."""
        if name in _IMMUTABLE_EVALUATION_ATTRIBUTES:
            raise ImmutableEvaluationAttributeError(f"'{name}' is immutable after creation")
        super().__setattr__(name, value)

    @classmethod
    def restore(cls, view: EvaluationView) -> Evaluation:
        """Bring an Evaluation back with its preserved verdict (called only by ``Run.restore``).

        The view holds every field of the entity (RUN_RESTORE_SPEC §2). The verdict is not
        decided again, only put back (ADR-0024).
        """
        evaluation = cls(
            evaluation_id=view.evaluation_id,
            run_id=view.run_id,
            artifact_ref=view.artifact_ref,
            kind=view.kind,
        )
        evaluation._status = view.status
        evaluation._flags = view.flags
        return evaluation

    @property
    def artifact_ref(self) -> str:
        """The candidate Artifact under evaluation (used by Run's approval gate)."""
        return self._artifact_ref

    @property
    def status(self) -> EvaluationStatus:
        """The current verdict state (used by Run's approval gate)."""
        return self._status

    @property
    def view(self) -> EvaluationView:
        """A read-only snapshot of the current state (ADR-0018 §4)."""
        return EvaluationView(
            evaluation_id=self._evaluation_id,
            run_id=self._run_id,
            artifact_ref=self._artifact_ref,
            kind=self._kind,
            status=self._status,
            flags=self._flags,
        )

    def decide(self, verdict: EvaluationStatus, flags: tuple[str, ...]) -> None:
        """Record the verdict and its flags exactly once (ADR-0018 §4).

        ``verdict`` must be terminal and the evaluation must still be ``PENDING``; both are
        validated here, leaving the evaluation unchanged on a violation.
        """
        if self._status is not EvaluationStatus.PENDING:
            raise InvalidEvaluationTransitionError(
                f"evaluation {self._evaluation_id} is already decided"
            )
        if verdict not in _TERMINAL_VERDICTS:
            raise InvalidEvaluationTransitionError(f"{verdict} is not a valid evaluation verdict")
        self._status = verdict
        self._flags = flags
